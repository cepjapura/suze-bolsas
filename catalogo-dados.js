window.getSuzeCatalog = function() {
    try {
        const saved = localStorage.getItem(window.SUZE_CATALOG_STORAGE_KEY);
        if (saved) {
            const parsed = JSON.parse(saved);
            if (Array.isArray(parsed) && parsed.length > 0) {
                return parsed;
            }
        }
    } catch (e) {
        console.warn('Erro ao ler catálogo personalizado:', e);
    }
    return window.SUZE_DEFAULT_CATALOG;
};

window.saveSuzeCatalog = function(items) {
    try {
        localStorage.setItem(window.SUZE_CATALOG_STORAGE_KEY, JSON.stringify(items));
        // Quando rodando no servidor da Hostinger (http/https), salva no servidor para todos os clientes
        if (window.location.protocol.startsWith('http')) {
            fetch('api-servidor.php?action=save_catalog', {
                method: 'POST',
                headers: { 'Content-Type': 'application/json' },
                body: JSON.stringify({ items: items })
            }).catch(() => {});
        }
        return true;
    } catch (e) {
        console.error('Erro ao salvar catálogo:', e);
        return false;
    }
};

window.syncCatalogFromHostinger = async function(onUpdated) {
    if (!window.location.protocol.startsWith('http')) return;
    try {
        const res = await fetch('api-servidor.php?action=get_catalog');
        if (!res.ok) return;
        const data = await res.json();
        if (Array.isArray(data) && data.length > 0) {
            localStorage.setItem(window.SUZE_CATALOG_STORAGE_KEY, JSON.stringify(data));
            if (typeof onUpdated === 'function') onUpdated(data);
        }
    } catch (e) {
        // Fallback silencioso para catálogo padrão
    }
};
